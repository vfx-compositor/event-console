/**
 * PGM FREEZE (U75) — 출력 **화면만** 그 자리에 얼린다. 순수 함수만.
 *
 * ## 무엇을 얼리고 무엇을 얼리지 않는가
 * 얼리는 것은 **상태에서 그림으로 가는 길**이다: 씬 렌더·오버레이·전환·씬 페이드·큐가 미는
 * 영상/오버레이 단계. 그래서 운영자는 얼어붙은 화면 뒤에서 다음 씬을 미리 세팅하고, 점수를
 * 고치고, 큐를 옮겨 둘 수 있다 — 화면에는 아무것도 새어 나가지 않는다.
 *
 * 얼리지 **않는** 것:
 *  - **소리** — 음악 덱·볼륨 축·게인은 라이브 상태를 그대로 따른다. 화면을 세운 이유가
 *    대개 "화면만 정리하는 동안 BGM은 계속"이기 때문이다.
 *  - **카메라 스트림** — 스트림은 상태가 아니라 장치다. 중계 화면을 얼려도 카메라 그림 자체는
 *    계속 움직인다(정지 화면을 원하면 암전이나 다른 씬을 쓴다).
 *  - **시간 기반 타이머** — 스냅샷의 `endsAt`은 절대 시각이라 스냅샷을 읽어도 계속 흐른다.
 *    별도 처리가 필요 없다는 뜻이고, 그게 맞는 동작이다(남은 시간은 실제로 줄고 있다).
 *  - **암전·리플레이** — 운영자가 즉시 손대야 하는 조작이라 라이브를 따른다.
 *
 * ## 왜 스냅샷을 하나로 두는가
 * 시각 경로가 여럿인데 각자 "얼었나?"를 물으면 한 프레임 안에서 어떤 것은 옛 상태를, 어떤
 * 것은 새 상태를 그린다(스코어바만 갱신된 얼어붙은 화면 — 최악의 사고다). 갈림길을
 * `selectVisualState` 하나로 두고, 모든 시각 경로가 그 결과 하나를 읽는다.
 */

/**
 * 지금 화면이 그려야 할 상태. 얼어 있고 스냅샷이 있으면 스냅샷, 그 외에는 라이브.
 *
 * 스냅샷이 없는 동결(부팅 직후 저장본이 `frozen: true`인 경우)은 **라이브로 떨어진다** —
 * 그리지 못하는 상태로 굳는 것보다 지금 상태를 그리는 편이 언제나 낫다. display가 다음
 * 프레임에 스냅샷을 잡으므로 화면은 그 지점에서 얼어붙는다.
 */
export function selectVisualState<T>(frozen: boolean, snapshot: T | null, live: T): T {
  return frozen && snapshot !== null ? snapshot : live;
}

/**
 * 상단 바 토글의 표시 (순수 — 테스트가 문구를 잠근다).
 *
 * 위험 조작이라 **색 + 형태 + 텍스트** 셋으로 동시에 알린다. 얼어 있는 동안 라벨이
 * `FREEZE 해제`로 바뀌는 것이 "지금 얼어 있다"의 가장 강한 신호다 — 버튼 하나만 보고도
 * 현재 상태를 알 수 있어야 한다.
 */
export function freezeToggleView(frozen: boolean): {
  label: string;
  pressed: boolean;
  tip: string;
} {
  return {
    label: frozen ? '■ FREEZE 해제' : '● PGM FREEZE',
    pressed: frozen,
    tip: frozen
      ? '출력 화면이 얼어 있습니다. 누르면 지금 상태로 즉시 컷 전환합니다(전환 효과 없음). 얼어 있는 동안에도 음악·볼륨은 그대로 조작할 수 있고, 카메라와 타이머는 계속 흐릅니다.'
      : '출력 화면을 지금 그림에 고정합니다. 얼어 있는 동안 씬·오버레이·전환을 미리 세팅해도 화면에는 나가지 않습니다. 음악·볼륨은 계속 조작할 수 있고, 카메라 그림과 타이머는 멈추지 않습니다. 해제하면 그 순간 상태로 컷 전환합니다.',
  };
}
